// Mac Info.plist entries shared by the Dev/worktree app (scripts/dev-electron.ts) and the packaged app
// (scripts/package-electron.ts). macOS shows these privacy usage descriptions in its permission prompts;
// a key missing from the bundle can make the request fail or never prompt (#1135), so both apps declare
// the same set. Pure data and hashing only: no IO, so `scripts/mac-app-info-check.ts` runs on any OS.
import {createHash} from 'node:crypto';

