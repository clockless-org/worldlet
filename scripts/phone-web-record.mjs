// The phones' copy of the built-in browser's page observer (platform/bridge/web-record.js), for websites they open in
// their own browser (owner request 2026-10-07; core/phone/README.md). The observer is the computer's own; only how it
// reports differs: on the iPhone to the `worldletRecord` message handler in its own script world, on Android to the
// `WorldletAndroid` bridge. `node scripts/phone-web-record.mjs` writes both copies, `--check` fails when one is stale.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {installWebRecorder} from '../platform/bridge/web-record.js';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const PHONE_WEB_RECORD_FILES=['ios/App/web-record.js','android/app/src/main/assets/web-record.js'];
export function phoneWebRecordScript(){
 return `// Generated by scripts/phone-web-record.mjs from platform/bridge/web-record.js; do not edit.
(function(){
var worldletRecord=function(text){try{if(window.webkit&&window.webkit.messageHandlers&&window.webkit.messageHandlers.worldletRecord)window.webkit.messageHandlers.worldletRecord.postMessage(text);else if(window.WorldletAndroid)window.WorldletAndroid.record(text);}catch(e){}};
(${installWebRecorder.toString()})();
})();
`;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const script=phoneWebRecordScript(),check=process.argv.includes('--check');
 const stale=PHONE_WEB_RECORD_FILES.filter(file=>{const full=path.join(root,file);return !fs.existsSync(full)||fs.readFileSync(full,'utf8')!==script;});
 if(check){if(stale.length){console.error('Stale phone observer copies (run node scripts/phone-web-record.mjs): '+stale.join(', '));process.exit(1);}console.log('PASS the phones carry the built-in browser\'s page observer');}
 else for(const file of stale)fs.writeFileSync(path.join(root,file),script);
}
