// One way to bring a person's own Agent into Fox (owner request 2026-10-03: OpenClaw, Claude Code,
// pi and Hermes Agent all come over through the same flow; Codex's conversations too, though Codex
// itself stays Fox's model rather than an Agent Fox replaces). Each Agent keeps its own files; the host
// reads them read-only into the same shape (conversations, notes, skills, scheduled jobs) and this
// module holds the shared rules: what each source is called, how its transcript lines become turns,
// how its scheduled jobs become Fox routines and what Fox remembers about what came over.
// OpenClaw's own rules (channels, agents, cron payloads) stay in `openclaw-migration`.
// Kept ES-compatible for JavaScriptCore and Jint.
import {agentRoleSkill,openClawSkillMarkdown,openClawSkillName,openClawTurn,type AgentRole,type OpenClawRoutine,type OpenClawRoutineResult,type OpenClawTurn} from './openclaw-migration.ts';

export type MigrationSource='openclaw'|'claude-code'|'pi'|'hermes'|'codex';
export const MIGRATION_SOURCES:MigrationSource[]=['openclaw','claude-code','pi','hermes','codex'];
export const isMigrationSource=(value:unknown):value is MigrationSource=>MIGRATION_SOURCES.includes(value as MigrationSource);
export const MIGRATION_SOURCE_TITLES:Record<MigrationSource,string>={openclaw:'OpenClaw','claude-code':'Claude Code',pi:'pi',hermes:'Hermes Agent',codex:'Codex'};
export type MigrationTurn=OpenClawTurn;
export type MigrationRoutine=OpenClawRoutine;
export type MigrationRoutineResult=OpenClawRoutineResult;

const record=(value:unknown):Record<string,any>=>value&&typeof value==='object'&&!Array.isArray(value)?value as Record<string,any>:{};
const text=(value:unknown)=>typeof value==='string'?value.trim():'';
const clip=(value:string,limit:number)=>value.length>limit?value.slice(0,limit-1).trimEnd()+'…':value;
const iso=(value:unknown):string|null=>{
 const date=typeof value==='number'&&Number.isFinite(value)?new Date(value<1e12?value*1000:value):typeof value==='string'&&value?new Date(value):null;
 return date&&!Number.isNaN(date.getTime())?date.toISOString().replace(/\.\d+Z$/,'Z'):null;
};
const firstLine=(value:string)=>clip(value.replace(/\s+/g,' ').trim(),60);

