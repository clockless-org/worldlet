/** A short line in Fox's long-term memory saying what came over and where it is. */
export function migrationMemoryNote({source,conversations,routines,skills,notes}:{source:MigrationSource;conversations:string[];routines:string[];skills:string[];notes:number}):string {
 const list=(items:string[],limit:number)=>items.slice(0,limit).join(', ')+(items.length>limit?` and ${items.length-limit} more`:'');
 const title=MIGRATION_SOURCE_TITLES[source];
 const lines=[`Brought over from ${title} on this computer:`];
 if(conversations.length)lines.push(`- Past conversations (search with read_companion_archive): ${list(conversations,12)}.`);
 if(notes)lines.push(`- ${notes} notes, searchable as "${title} notes".`);
 if(skills.length)lines.push(`- Skills: ${list(skills,12)}.`);
 if(routines.length)lines.push(`- Routines: ${list(routines,12)}.`);
 return lines.length>1?clip(lines.join('\n'),2400):'';
}

// Skills ---------------------------------------------------------------------------------------

/** A Hermes skill folder name: lowercase letters, digits and hyphens. */
export const migrationSkillName=openClawSkillName;
const SKILL_FOLDER=/^[a-z0-9]+(?:-[a-z0-9]+)*$/;
// One name inside a skill folder: no separators, drive or stream colon or control characters, no
// leading dot (so never `.` or `..`) and nothing Windows would trim.
const skillSegment=(part:string)=>part.length>0&&part.length<=128&&!/[/\\:\u0000-\u001f]/.test(part)&&!part.startsWith('.')&&!/[. ]$/.test(part);
/** The path parts of one brought skill file, or null when it is not a shape bringing an Agent
 * makes: `folder` is a `migrationSkillName` (perhaps with a `-2` suffix) and `relative` is up to
 * three plain names ending in a Markdown file. Skills and their stores come back from backups, so
 * nothing else is ever written into the Harness. */
export function migrationSkillPath(folder:unknown,relative:unknown):string[]|null {
 if(typeof folder!=='string'||typeof relative!=='string'||folder.length>64||!SKILL_FOLDER.test(folder)||!/\.md$/i.test(relative))return null;
 const parts=relative.split('/');
 return parts.length<=3&&parts.every(skillSegment)?[folder,...parts]:null;
}
/** Whether every folder and file of a brought skill store is a `migrationSkillPath`. */
export const migrationSkillsSafe=(skills:unknown):boolean=>!!skills&&typeof skills==='object'&&!Array.isArray(skills)&&
 Object.entries(skills as Record<string,unknown>).every(([folder,files])=>!!files&&typeof files==='object'&&!Array.isArray(files)&&
  Object.entries(files as Record<string,unknown>).every(([relative,text])=>typeof text==='string'&&migrationSkillPath(folder,relative)!==null));
/** Hermes lists a skill by the `name` and `description` in its SKILL.md frontmatter. Claude Code
 * and pi let both default (folder name, first paragraph), so they are filled in when missing. */
export function migrationSkillMarkdown(markdown:string,folder:string,source:MigrationSource):string {
 const match=/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(markdown);
 const front=match?match[1]:'',body=match?markdown.slice(match[0].length):markdown;
 const has=(key:string)=>new RegExp('^'+key+'\\s*:\\s*\\S','m').test(front);
 const added:string[]=[];
 if(!has('name'))added.push('name: '+migrationSkillName(folder));
 if(!has('description')){
  const paragraph=body.split(/\n\s*\n/).map(part=>part.replace(/^#+\s.*$/gm,'').replace(/\s+/g,' ').trim()).find(Boolean)??'';
  added.push('description: '+JSON.stringify(clip(paragraph||`${MIGRATION_SOURCE_TITLES[source]} skill ${folder}.`,300)));
 }
 if(!added.length)return markdown;
 return `---\n${[...added,...front?[front]:[]].join('\n')}\n---\n\n${body.replace(/^\s+/,'')}`;
}

const frontmatter=(markdown:string)=>{
 const match=/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(String(markdown||''));
 const field=(key:string)=>{const line=match?new RegExp('^'+key+'\\s*:\\s*(.+)$','m').exec(match[1]):null;return line?line[1].trim().replace(/^(["'])(.*)\1$/,'$2'):'';};
 return {field,body:(match?markdown.slice(match[0].length):String(markdown||'')).trim()};
};
/** A Claude Code sub-agent (`agents/<name>.md`: a role with its own instructions) as a skill Fox
 * loads when the person asks for that kind of work. */
export function claudeCodeAgentSkill(file:string,markdown:string):{name:string;markdown:string}|null {
 const {field,body}=frontmatter(markdown),label=field('name')||file.replace(/\.md$/i,'');
 if(!body)return null;
 const name=migrationSkillName('claude-agent-'+label),what=field('description');
 return {name,markdown:openClawSkillMarkdown({name,source:'claude-code',description:`The person's Claude Code sub-agent ${label}${what?': '+what:''}. Use it when they ask for that kind of work.`,
  body:`# ${label}\n\nIn Claude Code the person had a sub-agent called ${label}${what?' ('+clip(what.replace(/\s+/g,' '),300)+')':''}. Take on its role when they ask for that kind of work, following its instructions:\n\n${clip(body,40000)}`})};
}
/** A saved prompt the person runs by name (a Claude Code `/command`, a pi prompt template) as a skill. */
export function promptTemplateSkill(source:MigrationSource,file:string,markdown:string):{name:string;markdown:string}|null {
 const {field,body}=frontmatter(markdown),command=file.replace(/\.md$/i,'').replace(/[\\/]/g,':');
 if(!body)return null;
 const name=migrationSkillName(command+'-command'),what=field('description'),title=MIGRATION_SOURCE_TITLES[source];
 return {name,markdown:openClawSkillMarkdown({name,source,description:`The person's /${command} command from ${title}${what?': '+what:''}. Use it when they ask for /${command} or that task.`,
  body:`# /${command}\n\nIn ${title} the person ran this as /${command}. When they ask for it, or for that task, follow these instructions; $ARGUMENTS, $1, $2 … stand for what they add after the command.\n\n${clip(body,40000)}`})};
}
