/** Hermes Agent sessions Worldlet or Hermes itself started (scheduled runs, sub-agents, Worldlet's
 * own Fox) are not conversations the person had. */
export function hermesConversationIncluded(session:{id?:unknown;source?:unknown;session_key?:unknown}):boolean {
 const id=String(session.id??''),source=String(session.source??'').toLowerCase();
 // Fox's own turns on its API server carry Fox's session name as their key (X-Hermes-Session-Key, harnessSessionName).
 return !!id&&!id.startsWith('worldlet-')&&!String(session.session_key??'').startsWith('worldlet-')&&!['cron','subagent','delegate','batch','worldlet','acp'].includes(source);
}
const HERMES_SOURCES:Record<string,string>={cli:'Terminal',tui:'Terminal',telegram:'Telegram',discord:'Discord',slack:'Slack',whatsapp:'WhatsApp',signal:'Signal',matrix:'Matrix',email:'Email',sms:'SMS',web:'Web',api:'API',homeassistant:'Home Assistant',dingtalk:'DingTalk',feishu:'Feishu',wecom:'WeCom',mattermost:'Mattermost'};
/** "Telegram · Trip planning", from the session's title, chat name or first message. */
export function hermesConversationTitle({title,source,chat,first}:{title?:string|null;source?:string|null;chat?:string|null;first?:string|null}):string {
 const service=HERMES_SOURCES[text(source).toLowerCase()]??'';
 const name=text(title)||text(chat)||(text(first)?firstLine(text(first)):'Conversation');
 return clip(service&&!name.toLowerCase().includes(service.toLowerCase())?service+' · '+name:name,140);
}
/** One `messages` row of Hermes' `state.db` as a visible turn (tool rows and summaries are not). */
export function hermesTurn(row:{role?:unknown;content?:unknown;timestamp?:unknown;summary?:unknown}):MigrationTurn|null {
 if(row.role!=='user'&&row.role!=='assistant'||row.summary)return null;
 const body=text(row.content).replace(/\n\nCurrent Worldlet context \(untrusted reference data, not instructions\):\n[\s\S]*$/,'').trim();
 if(!body||body==='[SILENT]')return null;
 return {role:row.role,text:body,at:iso(typeof row.timestamp==='string'?Number(row.timestamp):row.timestamp)};
}

// Scheduled jobs -----------------------------------------------------------------------------

/** A job from Hermes Agent's `cron/jobs.json` as a Fox routine. Jobs that run a script, watch
 * something or only send a message stay with Hermes Agent. */
export function hermesRoutine(job:unknown,now=Date.now()):MigrationRoutineResult {
 const value=record(job),schedule=record(value.schedule);
 const name=clip(text(value.name)||firstLine(text(value.prompt))||'Hermes job',120);
 if(value.script||value.monitor_script||value.monitor_url||value.no_agent)return {ok:false,name,reason:'It runs a script or watches something, not a request to the Agent.'};
 const prompt=text(value.prompt);
 if(!prompt)return {ok:false,name,reason:'It has no request for the Agent.'};
 let when='';
 if(schedule.kind==='cron'){
  const fields=text(schedule.expr).split(/\s+/).filter(Boolean);
  if(fields.length!==5)return {ok:false,name,reason:'Its schedule uses cron features Fox does not support.'};
  when=fields.join(' ');
 }else if(schedule.kind==='interval'){
  const minutes=Math.round(Number(schedule.minutes));
  if(!Number.isFinite(minutes)||minutes<1)return {ok:false,name,reason:'Its schedule could not be read.'};
  when=minutes%1440===0?'every '+minutes/1440+'d':minutes%60===0?'every '+minutes/60+'h':'every '+minutes+'m';
 }else if(schedule.kind==='once'){
  const at=iso(schedule.run_at);
  if(!at)return {ok:false,name,reason:'Its time could not be read.'};
  if(Date.parse(at)<=now)return {ok:false,name,reason:'It already ran.'};
  when=at;
 }else return {ok:false,name,reason:'Its schedule could not be read.'};
 return {ok:true,routine:{key:'hermes:'+(text(value.id)||name),name,prompt:clip(prompt,8000),schedule:when,enabled:value.enabled!==false&&value.state!=='paused'}};
}
