/** Claude Code's harness inserts these into user messages; they are not what the person typed. */
const CLAUDE_TAGS=/<(system-reminder|command-name|command-message|command-args|local-command-stdout|local-command-stderr|local-command-caveat|bash-input|bash-stdout|bash-stderr|user-prompt-submit-hook|session-start-hook)>[\s\S]*?<\/\1>/g;
/** One line of a Claude Code session file (`projects/<folder>/<id>.jsonl`) as a visible turn, or
 * null for tool calls and results, thinking, summaries, side chains and harness lines. */
export function claudeCodeTurn(line:unknown):MigrationTurn|null {
 const entry=record(line);
 if(entry.type!=='user'&&entry.type!=='assistant')return null;
 if(entry.isMeta||entry.isSidechain||entry.isCompactSummary||entry.isVisibleInTranscriptOnly)return null;
 const message=record(entry.message),content=message.content;
 if(message.role!==entry.type)return null;
 let body=typeof content==='string'?content:Array.isArray(content)?content.map(part=>{const p=record(part);return p.type==='text'&&typeof p.text==='string'?p.text:'';}).filter(Boolean).join('\n\n'):'';
 body=body.replace(CLAUDE_TAGS,'').trim();
 if(!body||/^\[Request interrupted by user/.test(body)||body.startsWith('Caveat: The messages below were generated by the user while running local commands'))return null;
 return {role:entry.type,text:body,at:iso(entry.timestamp)};
}
/** "worldlet · Fix the sign-in redirect": the project folder, then the session's own name. */
export function claudeCodeConversationTitle({title,cwd,first}:{title?:string|null;cwd?:string|null;first?:string|null}):string {
 const folder=text(cwd).split(/[\\/]/).filter(Boolean).at(-1)??'';
 const name=text(title)||(text(first)?firstLine(text(first)):'Conversation');
 return clip(folder&&!name.toLowerCase().startsWith(folder.toLowerCase())?folder+' · '+name:name,140);
}
/** One line of a Codex session file (`sessions/YYYY/MM/DD/rollout-*.jsonl`) as a visible turn: only
 * what the person typed and Codex's answers, never the instructions, environment context, reasoning
 * or tool calls Codex also records. Older Codex wrote them as `event_msg` user_message /
 * agent_message; current Codex (and the ChatGPT app's) as `event_msg` item_completed with a
 * UserMessage / AgentMessage item. */
export function codexTurn(line:unknown):MigrationTurn|null {
 const entry=record(line),payload=record(entry.payload);
 if(entry.type!=='event_msg')return null;
 if(payload.type==='item_completed'){
  const item=record(payload.item);
  if(item.type!=='UserMessage'&&item.type!=='AgentMessage')return null;
  const body=(Array.isArray(item.content)?item.content:[]).map(part=>{const p=record(part);return /^text$/i.test(String(p.type))?text(p.text):'';}).filter(Boolean).join('\n\n');
  return body?{role:item.type==='UserMessage'?'user':'assistant',text:body,at:iso(entry.timestamp)}:null;
 }
 if(payload.type!=='user_message'&&payload.type!=='agent_message')return null;
 const body=text(payload.message);
 if(!body)return null;
 return {role:payload.type==='user_message'?'user':'assistant',text:body,at:iso(entry.timestamp)};
}
/** The visible turns of one Codex session file; a file holding both forms keeps only the current one. */
export function codexTurns(lines:unknown[]):MigrationTurn[] {
 const current=lines.filter(line=>record(record(line).payload).type==='item_completed');
 const turns=current.map(codexTurn).filter((turn):turn is MigrationTurn=>!!turn);
 return turns.length?turns:lines.map(codexTurn).filter((turn):turn is MigrationTurn=>!!turn);
}
